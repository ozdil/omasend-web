type Child = Node | string | null | undefined | false;

/**
 * Minimal DOM builder. Text children are always inserted as text nodes,
 * so values coming from the engine or the network can never become markup.
 */
function el<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  attrs: Record<string, string> = {},
  ...children: Child[]
): HTMLElementTagNameMap[K] {
  const node = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs)) {
    if (key === 'class') node.className = value;
    else node.setAttribute(key, value);
  }
  for (const child of children) {
    if (child === null || child === undefined || child === false) continue;
    node.append(child);
  }
  return node;
}

/** Escapes & < > " ' for the rare case where a string must go into HTML markup. */
export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

const LOGO_SVG = `
  <svg class="header-logo" viewBox="0 0 64 64" fill="none" aria-hidden="true">
    <rect width="64" height="64" rx="14" fill="#0284c7" opacity="0.2"/>
    <circle cx="32" cy="32" r="20" stroke="#38bdf8" stroke-width="3" opacity="0.6"/>
    <circle cx="32" cy="32" r="8" fill="#22c55e"/>
  </svg>`;

const INFO_SVG = `
  <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true">
    <circle cx="12" cy="12" r="10"/>
    <line x1="12" y1="16" x2="12" y2="12"/>
    <line x1="12" y1="8" x2="12.01" y2="8"/>
  </svg>`;

const DEVICE_SVG = `
  <svg width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#22c55e" stroke-width="2" aria-hidden="true">
    <rect x="2" y="3" width="20" height="14" rx="2"/>
    <line x1="8" y1="21" x2="16" y2="21"/>
    <line x1="12" y1="17" x2="12" y2="21"/>
  </svg>`;

/** Static, constant SVG markup only — never pass dynamic values here. */
function staticSvg(markup: string): Element {
  const tpl = document.createElement('template');
  tpl.innerHTML = markup.trim();
  return tpl.content.firstElementChild as Element;
}

export class OmaSendApp {
  private vault: StorageVault;
  private engineClient: EngineClient;

  private omaId = '';
  private lastStatus: EngineStatusResult | null = null;
  private pollInterval: number | null = null;

  constructor() {
    this.vault = new StorageVault();
    this.engineClient = new EngineClient();
  }

  public async init(): Promise<void> {
    this.omaId = this.vault.getOrCreateOmaId();
    this.renderLayout();
    await this.refresh();
    this.startBackgroundLoop();
  }

  private renderLayout(): void {
    const appEl = document.getElementById('app');
    if (!appEl) return;

    const formattedId = OmaIdValidator.format(this.omaId);

    const copyIdBtn = el(
      'button',
      {
        class: 'omaid-pill',
        id: 'btn-copy-my-id',
        type: 'button',
        title: 'Local ID generated by this browser. It is not registered with any device; click to copy.',
      },
      el('span', { class: 'omaid-label' }, 'BROWSER ID:'),
      el('span', { class: 'omaid-value', id: 'display-oma-id' }, formattedId),
    );
    copyIdBtn.addEventListener('click', () => {
      void this.copyText(formattedId, 'ID copied to clipboard');
    });

    const infoBtn = el('button', {
      class: 'btn btn-ghost btn-icon',
      id: 'btn-show-info',
      type: 'button',
      title: 'About OmaSend Web',
      'aria-label': 'About OmaSend Web',
    }, staticSvg(INFO_SVG));
    infoBtn.addEventListener('click', () => this.showInfoModal());

    const header = el(
      'header',
      { class: 'app-header' },
      el(
        'div',
        { class: 'header-brand' },
        staticSvg(LOGO_SVG),
        el(
          'div',
          { class: 'header-titles' },
          el('div', { class: 'app-title' }, 'OmaSend ', el('span', { class: 'badge badge-verified' }, `v${__APP_VERSION__}`)),
          el('div', { class: 'app-subtitle' }, 'Web client (preview)'),
        ),
      ),
      el('div', { class: 'header-actions' }, copyIdBtn, infoBtn),
    );

    const notice = el(
      'section',
      { class: 'card glass-card panel-notice', role: 'status' },
      el('div', { class: 'card-header' }, el('div', { class: 'card-title' }, 'Sending and pairing are not available in the browser yet')),
      el(
        'p',
        { class: 'notice-text' },
        'This web client cannot send files, sync the clipboard or pair devices yet. ',
        'To send files and pair devices, use the OmaSend desktop panel or the OmaSend Android app.',
      ),
    );

    const peersPanel = el(
      'section',
      { class: 'card glass-card panel-radar' },
      el(
        'div',
        { class: 'card-header' },
        el('div', { class: 'card-title' }, 'Devices seen by the engine'),
        el('span', { class: 'badge badge-muted', id: 'peer-count-badge' }, '0 devices'),
      ),
      el('div', { class: 'peers-list', id: 'peers-list-container' }),
    );

    const footer = el(
      'footer',
      { class: 'app-footer' },
      el(
        'div',
        { class: 'footer-status' },
        el('span', { class: 'engine-badge', id: 'engine-status-indicator' }, 'CHECKING ENGINE…'),
        el('span', { class: 'footer-separator' }, '•'),
        el('span', { id: 'footer-connection-text' }, ''),
      ),
    );

    appEl.replaceChildren(
      el('div', { class: 'app-container' }, header, el('main', { class: 'dashboard-grid' }, notice, peersPanel), footer),
      el('div', { id: 'modal-container' }),
    );
  }

  private async refresh(): Promise<void> {
    await this.refreshEngineStatus();
    await this.refreshPeers();
  }

  private async refreshEngineStatus(): Promise<void> {
    const result = await this.engineClient.getStatus();
    this.lastStatus = result;
    const statusEl = document.getElementById('engine-status-indicator');
    const footerEl = document.getElementById('footer-connection-text');
    if (result.ok) {
      const st = result.status;
      if (statusEl) {
        statusEl.className = 'engine-badge engine-online';
        statusEl.textContent = st.version ? `ENGINE CONNECTED v${st.version}` : 'ENGINE CONNECTED';
      }
      if (footerEl) {
        const parts = [`Port ${st.port ?? 'unknown'}`];
        if (st.device_name) parts.push(st.device_name);
        footerEl.textContent = parts.join(' • ');
      }
    } else {
      if (statusEl) {
        statusEl.className = 'engine-badge';
        statusEl.textContent = 'ENGINE NOT CONNECTED';
      }
      if (footerEl) footerEl.textContent = result.reason;
    }
  }

  private async refreshPeers(): Promise<void> {
    const container = document.getElementById('peers-list-container');
    const badge = document.getElementById('peer-count-badge');
    if (!container) return;

    const devices: DiscoveredDevice[] = this.lastStatus?.ok ? await this.engineClient.getDiscoveredDevices() : [];
    if (badge) badge.textContent = `${devices.length} ${devices.length === 1 ? 'device' : 'devices'}`;

    if (devices.length === 0) {
      const text = this.lastStatus?.ok
        ? 'The engine has not discovered any devices on the local network.'
        : 'No engine connected, so no devices can be listed.';
      container.replaceChildren(el('div', { class: 'empty-state' }, el('div', { class: 'empty-text' }, text)));
      return;
    }

    container.replaceChildren(
      ...devices.map((dev) => {
        const addr = dev.ip ? (dev.port ? `${dev.ip}:${dev.port}` : dev.ip) : 'address unknown';
        const item = el(
          'div',
          { class: 'peer-item' },
          el('div', { class: 'peer-avatar' }, staticSvg(DEVICE_SVG)),
          el(
            'div',
            { class: 'peer-info' },
            el('div', { class: 'peer-name' }, dev.name),
            el('div', { class: 'peer-sub' }, `${addr} • ${dev.transport}`),
          ),
        );
        item.dataset.devId = dev.id;
        return item;
      }),
    );
  }

  private showInfoModal(): void {
    const modalContainer = document.getElementById('modal-container');
    if (!modalContainer) return;

    const row = (key: string, value: string, highlight = false) =>
      el('div', { class: 'info-row' }, el('span', { class: 'info-key' }, key), el('span', { class: highlight ? 'info-val highlight' : 'info-val' }, value));

    const closeX = el('button', { class: 'btn-close', type: 'button', 'aria-label': 'Close' }, 'X');
    const closeBtn = el('button', { class: 'btn btn-primary', type: 'button' }, 'Close');
    closeX.addEventListener('click', () => this.closeModal());
    closeBtn.addEventListener('click', () => this.closeModal());

    modalContainer.replaceChildren(
      el(
        'div',
        { class: 'modal-backdrop' },
        el(
          'div',
          { class: 'modal-card', role: 'dialog', 'aria-modal': 'true' },
          el('div', { class: 'modal-header' }, el('div', { class: 'modal-title' }, 'About OmaSend Web'), closeX),
          el(
            'div',
            { class: 'modal-body' },
            row('Application:', 'OmaSend Web Client (PWA)'),
            row('Version:', __APP_VERSION__, true),
            row('Developer:', 'Ozan Ozdil (ozdil)'),
            row('License:', 'MIT'),
            el(
              'div',
              { class: 'info-desc mt-3' },
              'Preview build. Shows the status of a configured OmaSend engine. ',
              'File transfer and pairing are done with the OmaSend desktop panel or Android app.',
            ),
          ),
          el('div', { class: 'modal-footer' }, closeBtn),
        ),
      ),
    );
  }

  private closeModal(): void {
    document.getElementById('modal-container')?.replaceChildren();
  }

  private async copyText(text: string, okMessage: string): Promise<void> {
    try {
      if (!navigator.clipboard?.writeText) throw new Error('Clipboard API unavailable');
      await navigator.clipboard.writeText(text);
      this.showToast(okMessage);
    } catch {
      this.showToast('Could not copy to the clipboard');
    }
  }

  private showToast(msg: string): void {
    const toast = el('div', { class: 'toast-notification', role: 'status' }, msg);
    document.body.appendChild(toast);
    setTimeout(() => {
      toast.classList.add('fade-out');
      setTimeout(() => toast.remove(), 300);
    }, 2500);
  }

  private startBackgroundLoop(): void {
    if (this.pollInterval) clearInterval(this.pollInterval);
    this.pollInterval = window.setInterval(() => {
      void this.refresh();
    }, 4000);
  }
}
